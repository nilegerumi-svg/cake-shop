function npcGradeLabel(e, n) {
  if (!NPC_FAMILY[e]) return "";
  const a = npcAgeOn(e, n),
    o = npcSchoolStage(e, n);
  return o === "below"
    ? `${a}岁 · 还没到入园年龄`
    : o === "kinder"
      ? `${a}岁 · 在幼儿园`
      : o === "primary"
        ? `${a}岁 · 小学${PRIMARY_GRADE_NAMES[a - 6] ?? ""}`
        : o === "middle"
          ? `${a}岁 · ${MIDDLE_GRADE_NAMES[a - 12] ?? "初中"}`
          : o === "high"
            ? `${a}岁 · ${HIGH_GRADE_NAMES[a - 15] ?? "高中"}`
            : `${a}岁 · 已高中毕业，在外地上大学`;
}

function npcSchoolPlace(e, n) {
  const s = npcSchoolStage(e, n);
  return s === "middle"
    ? "middleschool"
    : s === "high"
      ? "highschool"
      : s === "kinder" || s === "primary"
        ? "school"
        : null;
}

