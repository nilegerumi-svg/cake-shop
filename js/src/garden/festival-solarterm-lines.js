function solarTermLinesForDay(e) {
  const n = currentSolarTerm(e).name,
    s = SOLAR_TERMS.findIndex((o) => o.name === n),
    a = SOLAR_TERMS[(s - 1 + SOLAR_TERMS.length) % SOLAR_TERMS.length].name;
  return [n, a];
}

function solarTermLines(e) {
  return solarTermLinesForDay(e).flatMap((n) => SOLAR_TERM_LINES[n] ?? []);
}

