function npcAgeOn(e, n) {
  const s = NPC_FAMILY[e];
  return s ? s.startAge + Math.floor(Math.max(0, n - 1) / 120) : -1;
}

function npcSchoolStage(e, n) {
  if (!NPC_FAMILY[e]) return "away";
  const a = npcAgeOn(e, n);
  return a < 3
    ? "below"
    : a <= 5
      ? "kinder"
      : a <= 11
        ? "primary"
        : a <= 14
          ? "middle"
          : a <= 17
            ? "high"
            : "away";
}

