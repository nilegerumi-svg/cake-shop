function pickFestivalLine(e, n, s) {
  if (!e) return [];
  const a = e[n];
  if (a) {
    const l = a[s];
    if (l && l.length > 0) return l;
    const c = a["*"];
    if (c && c.length > 0) return c;
  }
  const o = e.any;
  if (o) {
    const l = o[s];
    if (l && l.length > 0) return l;
    const c = o["*"];
    if (c && c.length > 0) return c;
  }
  return [];
}

function festivalAmbientLine(e, n, s) {
  return pickFestivalLine(FESTIVAL_AMBIENT_LINES[e], placeKeyOf(n), s);
}

function festivalNpcLine(e, n, s) {
  return pickFestivalLine(FESTIVAL_NPC_LINES[e], placeKeyOf(n), s);
}

